#ifndef _GPS_SERVICE_H_
#define _GPS_SERVICE_H_

//====================================================================================================================
// 严禁在此模块中引用摄像头相关的任何头文件（解耦要求）
//====================================================================================================================

#include "zf_common_typedef.h"

//==================================================== 硬件配置 ====================================================
// 串口配置（使用主板P11接口）
#define GPS_UART                (UART_2)                    // 使用UART2
#define GPS_UART_TX_PIN         (UART2_TX_P10_1)            // MCU_TX -> GPS_RX
#define GPS_UART_RX_PIN         (UART2_RX_P10_0)            // MCU_RX <- GPS_TX
#define GPS_UART_BAUD           (115200)                    // 波特率（TAU1201默认115200）

// 缓冲区配置
#define GPS_LINE_BUFFER_SIZE    (128)                       // 单行NMEA语句缓冲区大小
#define GPS_SENTENCE_QUEUE_SIZE (8)                         // NMEA语句队列深度（支持连续接收）
//==================================================== 硬件配置 ====================================================


//==================================================== 信号质量阈值 ====================================================
#define GPS_HDOP_EXCELLENT      (1.0f)                      // HDOP < 1.0 优秀
#define GPS_HDOP_GOOD           (2.0f)                      // HDOP < 2.0 良好
#define GPS_HDOP_MODERATE       (4.0f)                      // HDOP < 4.0 中等
#define GPS_HDOP_UNRELIABLE     (4.0f)                      // HDOP >= 4.0 不可靠
//==================================================== 信号质量阈值 ====================================================


//==================================================== 坐标转换常量 ====================================================
// WGS-84椭球体参数
#define GPS_EARTH_RADIUS_M      (6378137.0)                 // 地球赤道半径（米）
#define GPS_DEG_TO_M_LAT        (111320.0)                  // 纬度1度约等于的米数
#define GPS_PI                  (3.14159265358979323846)    // 圆周率
#define GPS_DEG_TO_RAD          (GPS_PI / 180.0)            // 角度转弧度系数
#define GPS_RAD_TO_DEG          (180.0 / GPS_PI)            // 弧度转角度系数
//==================================================== 坐标转换常量 ====================================================


//==================================================== 数据类型定义 ====================================================

// GPS时间结构体（避免与zf_device_gnss.h冲突，使用svc前缀）
typedef struct
{
    uint16  year;                           // 年（2000-2099）
    uint8   month;                          // 月（1-12）
    uint8   day;                            // 日（1-31）
    uint8   hour;                           // 时（0-23，北京时间）
    uint8   minute;                         // 分（0-59）
    uint8   second;                         // 秒（0-59）
} gps_svc_time_struct;

// GPS定位状态枚举
typedef enum
{
    GPS_STATUS_INVALID      = 0,            // 无效定位（未锁定卫星）
    GPS_STATUS_VALID        = 1,            // 有效定位（已锁定卫星）
    GPS_STATUS_DGPS         = 2,            // 差分GPS定位
} gps_status_enum;

// GPS信号质量枚举
typedef enum
{
    GPS_QUALITY_UNKNOWN     = 0,            // 未知
    GPS_QUALITY_EXCELLENT   = 1,            // 优秀 (HDOP < 1.0)
    GPS_QUALITY_GOOD        = 2,            // 良好 (HDOP < 2.0)
    GPS_QUALITY_MODERATE    = 3,            // 中等 (HDOP < 4.0)
    GPS_QUALITY_UNRELIABLE  = 4,            // 不可靠 (HDOP >= 4.0)
} gps_quality_enum;

// NMEA解析器状态机枚举
typedef enum
{
    GPS_PARSE_IDLE          = 0,            // 空闲，等待'$'
    GPS_PARSE_HEADER        = 1,            // 正在接收语句头
    GPS_PARSE_BODY          = 2,            // 正在接收语句体
    GPS_PARSE_CHECKSUM1     = 3,            // 正在接收校验和高位
    GPS_PARSE_CHECKSUM2     = 4,            // 正在接收校验和低位
    GPS_PARSE_CR            = 5,            // 等待CR (\r)
    GPS_PARSE_LF            = 6,            // 等待LF (\n)
    GPS_PARSE_COMPLETE      = 7,            // 语句接收完成
} gps_parse_state_enum;

// NMEA语句类型枚举
typedef enum
{
    GPS_SENTENCE_UNKNOWN    = 0,            // 未知语句
    GPS_SENTENCE_RMC        = 1,            // $GNRMC / $GPRMC
    GPS_SENTENCE_GGA        = 2,            // $GNGGA / $GPGGA
} gps_sentence_type_enum;

// GPS数据结构体（核心接口）
typedef struct
{
    //-------------------- 定位状态 --------------------
    gps_status_enum     status;             // 定位状态（0:无效 1:有效 2:差分）
    uint8               satellite_count;    // 用于定位的卫星数量
    
    //-------------------- 位置信息（十进制度数） --------------------
    double              latitude;           // 纬度（十进制度数，北纬为正，南纬为负）
    double              longitude;          // 经度（十进制度数，东经为正，西经为负）
    float               altitude;           // 海拔高度（米）
    
    //-------------------- 局部坐标系（相对原点，单位：米） --------------------
    float               pos_x;              // X坐标（东向为正，单位：米）
    float               pos_y;              // Y坐标（北向为正，单位：米）
    uint8               origin_set;         // 原点是否已设置（0:未设置 1:已设置）
    
    //-------------------- 运动信息 --------------------
    float               speed;              // 地面速率（km/h）
    float               course;             // 航向角/地面航向（0.0-359.9度，以真北为参考）
    
    //-------------------- 信号质量 --------------------
    float               hdop;               // 水平精度因子（越小越好）
    gps_quality_enum    quality;            // 信号质量等级
    uint8               is_reliable;        // 数据是否可靠（1:可靠 0:不可靠，HDOP>=4.0）
    
    //-------------------- 时间信息 --------------------
    gps_svc_time_struct time;               // GPS时间（已转换为北京时间）
    
    //-------------------- 原始度分秒格式（调试用） --------------------
    uint16              lat_degree;         // 纬度 - 度
    uint16              lat_minute;         // 纬度 - 分（整数部分）
    uint16              lat_second;         // 纬度 - 秒（放大100倍）
    int8                lat_hemisphere;     // 纬度半球 'N'北 或 'S'南
    
    uint16              lon_degree;         // 经度 - 度
    uint16              lon_minute;         // 经度 - 分（整数部分）
    uint16              lon_second;         // 经度 - 秒（放大100倍）
    int8                lon_hemisphere;     // 经度半球 'E'东 或 'W'西
    
    //-------------------- 数据更新标志 --------------------
    vuint8              is_updated;         // 数据更新标志（1:已更新 0:未更新）
    uint32              update_timestamp;   // 最后更新时间戳（ms）
    
    //-------------------- 统计信息（调试用） --------------------
    uint32              rmc_count;          // RMC语句接收计数
    uint32              gga_count;          // GGA语句接收计数
    uint32              checksum_error_count;   // 校验和错误计数
    
} gps_data_struct;

// GPS原点结构体（局部坐标系参考点）
typedef struct
{
    double  latitude;                       // 原点纬度（十进制度数）
    double  longitude;                      // 原点经度（十进制度数）
    float   cos_lat;                        // cos(原点纬度)，预计算提高效率
    uint8   is_set;                         // 原点是否已设置
} gps_origin_struct;

//==================================================== 数据类型定义 ====================================================


//==================================================== 全局变量声明 ====================================================
extern gps_data_struct      gps_data;       // GPS数据（供外部模块读取）
extern gps_origin_struct    gps_origin;     // GPS原点（局部坐标系参考点）
//==================================================== 全局变量声明 ====================================================


//==================================================== 函数声明 ====================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     GPS服务模块初始化
// 参数说明     void
// 返回参数     void
// 使用示例     gps_service_init();
// 备注信息     初始化UART串口、配置中断接收、配置TAU1201模块参数、初始化状态机
//-------------------------------------------------------------------------------------------------------------------
void gps_service_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     GPS数据更新（主循环调用）
// 参数说明     void
// 返回参数     uint8           0-无新数据 1-有新数据已更新
// 使用示例     if(gps_service_update()) { /* 处理新数据 */ }
// 备注信息     从语句队列中取出完整语句并解析，更新gps_data结构体
//-------------------------------------------------------------------------------------------------------------------
uint8 gps_service_update(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     GPS串口接收中断回调（流式状态机版本）
// 参数说明     void
// 返回参数     void
// 使用示例     在 uart2_isr() 中调用 gps_uart_callback();
// 备注信息     逐字符读入，使用状态机识别完整语句，避免10Hz高频下丢包
//-------------------------------------------------------------------------------------------------------------------
void gps_uart_callback(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置GPS原点（将当前位置设为赛道起点）
// 参数说明     void
// 返回参数     uint8           0-设置失败（未定位） 1-设置成功
// 使用示例     if(gps_set_origin()) { printf("Origin set!\n"); }
// 备注信息     记录当前经纬度为局部坐标系原点，预计算cos(lat)提高后续转换效率
//-------------------------------------------------------------------------------------------------------------------
uint8 gps_set_origin(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置指定坐标为GPS原点
// 参数说明     lat             原点纬度（十进制度数）
// 参数说明     lon             原点经度（十进制度数）
// 返回参数     void
// 使用示例     gps_set_origin_manual(30.123456, 104.654321);
// 备注信息     手动指定原点坐标，用于已知起点的情况
//-------------------------------------------------------------------------------------------------------------------
void gps_set_origin_manual(double lat, double lon);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新局部坐标（LLH转Local XY）
// 参数说明     void
// 返回参数     void
// 使用示例     gps_update_local_xy();
// 备注信息     使用等距圆柱投影算法，将当前经纬度转换为相对原点的XY偏移（米）
//             X轴正方向：东   Y轴正方向：北
//             计算公式：x = (lon - lon0) * 111320 * cos(lat0)
//                       y = (lat - lat0) * 111320
//-------------------------------------------------------------------------------------------------------------------
void gps_update_local_xy(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     计算两点之间的距离（Haversine公式）
// 参数说明     lat1            第一个点的纬度（十进制度数）
// 参数说明     lon1            第一个点的经度（十进制度数）
// 参数说明     lat2            第二个点的纬度（十进制度数）
// 参数说明     lon2            第二个点的经度（十进制度数）
// 返回参数     double          两点之间的距离（单位：米）
// 使用示例     distance = gps_calc_distance(30.123, 104.456, 30.234, 104.567);
// 备注信息     使用WGS-84椭球体模型，精度约0.5%
//-------------------------------------------------------------------------------------------------------------------
double gps_calc_distance(double lat1, double lon1, double lat2, double lon2);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     计算从第一个点到第二个点的方位角
// 参数说明     lat1            第一个点的纬度（十进制度数）
// 参数说明     lon1            第一个点的经度（十进制度数）
// 参数说明     lat2            第二个点的纬度（十进制度数）
// 参数说明     lon2            第二个点的经度（十进制度数）
// 返回参数     double          方位角（0-360度，以真北为参考，顺时针）
// 使用示例     azimuth = gps_calc_azimuth(30.123, 104.456, 30.234, 104.567);
// 备注信息     
//-------------------------------------------------------------------------------------------------------------------
double gps_calc_azimuth(double lat1, double lon1, double lat2, double lon2);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检测GPS是否已定位
// 参数说明     void
// 返回参数     uint8           0-未定位 1-已定位
// 使用示例     if(gps_is_fixed()) { /* GPS已锁定卫星 */ }
// 备注信息     
//-------------------------------------------------------------------------------------------------------------------
uint8 gps_is_fixed(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检测GPS数据是否可靠
// 参数说明     void
// 返回参数     uint8           0-不可靠(HDOP>=4.0) 1-可靠
// 使用示例     if(gps_is_reliable()) { /* 数据可信 */ }
// 备注信息     
//-------------------------------------------------------------------------------------------------------------------
uint8 gps_is_reliable(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取到原点的距离
// 参数说明     void
// 返回参数     float           到原点的距离（米），未设置原点返回-1
// 使用示例     dist = gps_get_distance_to_origin();
// 备注信息     使用局部坐标系计算，效率高于经纬度直接计算
//-------------------------------------------------------------------------------------------------------------------
float gps_get_distance_to_origin(void);

//==================================================== 函数声明 ====================================================

#endif
